/** 危機關鍵字：偵測到時不呼叫模型，直接回覆求助資訊 */
const CRISIS_PATTERNS = [
  /自殺/,
  /想死/,
  /不想活/,
  /活不下去/,
  /輕生/,
  /割腕/,
  /自殘/,
  /傷害自己/,
  /結束(我的)?生命/,
  /kill\s*myself/i,
  /suicid/i,
  /self[-\s]?harm/i,
  /want\s+to\s+die/i,
];

export function detectCrisis(text: string): boolean {
  return CRISIS_PATTERNS.some((re) => re.test(text));
}

